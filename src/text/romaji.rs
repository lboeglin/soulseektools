//! Romaji transliteration, used to compare Japanese titles with romanised filenames.
//!
//! A streaming export lists `千本桜` while the file on disk is `Senbonzakura.flac`;
//! no amount of string similarity relates those two without transliterating one of
//! them first. Artist readings are less trustworthy than title readings -- aliases
//! frequently use non-standard readings -- which is why callers weight an artist
//! match lower than a title match.
//!
//! Words are read into kana with IPADIC, through lindera, and the kana spelled
//! out by [`kana_to_romaji`]. The dictionary is embedded, which is most of the
//! binary's size.

use std::borrow::Cow;
use std::collections::HashMap;
use std::sync::{LazyLock, Mutex, MutexGuard, PoisonError};

use lindera::dictionary::load_dictionary;
use lindera::mode::Mode;
use lindera::segmenter::Segmenter;
use regex::Regex;
use unicode_normalization::UnicodeNormalization;

use crate::text::kana::kana_to_romaji;
use crate::text::normalize::{is_space, normalize};

static JAPANESE_CHARACTER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"[\u{3040}-\u{309f}\u{30a0}-\u{30ff}\u{3400}-\u{4dbf}\u{4e00}-\u{9fff}\u{f900}-\u{faff}\u{ff66}-\u{ff9f}]",
    )
    .unwrap()
});

/// Report whether transliteration could change anything.
#[must_use]
pub fn contains_japanese(text: &str) -> bool {
    JAPANESE_CHARACTER.is_match(text)
}

/// Return the normalised Hepburn romanisation of `text`.
///
/// Text without Japanese characters is returned normalised and otherwise
/// untouched, so this is safe to call on every name unconditionally.
#[must_use]
pub fn to_romaji(text: &str) -> String {
    if let Some(cached) = cache().get(text) {
        return cached.clone();
    }

    let converted = if contains_japanese(text) {
        normalize(&transliterate(text))
    } else {
        normalize(text)
    };

    cache().insert(text.to_owned(), converted.clone());
    converted
}

/// Romanise each whitespace-separated run on its own, keeping the spaces that
/// were genuinely in the name and adding none at the word boundaries IPADIC
/// finds: `化けの花` is `bakenohana`, as the oracle has it.
fn transliterate(text: &str) -> String {
    text.split(is_space)
        .filter(|run| !run.is_empty())
        .map(|run| {
            let run: String = run.nfkc().collect();
            kana_to_romaji(&reading(&with_known_readings(&run)))
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// Read `run` into kana word by word, with IPADIC's reading for every word it
/// knows. A word it does not know keeps its surface, with each kanji in it given
/// the Unihan reading in [`KANJI_READINGS`]; text that is not Japanese is never
/// read, so a Latin word IPADIC happens to know keeps its spelling.
fn reading(run: &str) -> String {
    let Ok(mut tokens) = SEGMENTER.segment(Cow::Borrowed(run)) else {
        return run.to_owned();
    };

    let mut kana = String::with_capacity(run.len());
    for token in &mut tokens {
        let surface = token.surface.to_string();
        match token.details().get(IPADIC_READING) {
            Some(&reading) if reading != UNKNOWN && contains_japanese(&surface) => {
                kana.push_str(reading);
            }
            _ => {
                for c in surface.chars() {
                    match kanji_reading(c) {
                        Some(reading) => kana.push_str(reading),
                        None => kana.push(c),
                    }
                }
            }
        }
    }
    kana
}

/// The index of the reading, in katakana, among an IPADIC token's details.
const IPADIC_READING: usize = 7;

/// The placeholder IPADIC gives for a detail it does not have, as for every
/// detail of a word it does not know.
const UNKNOWN: &str = "*";

static SEGMENTER: LazyLock<Segmenter> = LazyLock::new(|| {
    let dictionary =
        load_dictionary("embedded://ipadic").expect("IPADIC is embedded in the binary");
    Segmenter::new(Mode::Normal, dictionary, None)
});

/// Every kanji's first Japanese reading, from Unihan, generated by
/// `scripts/unihan_readings.py`.
const KANJI_READINGS: &str = include_str!("kanji_readings.tsv");

fn kanji_reading(kanji: char) -> Option<&'static str> {
    static READINGS: LazyLock<HashMap<char, &'static str>> = LazyLock::new(|| {
        KANJI_READINGS
            .lines()
            .filter(|line| !line.starts_with('#'))
            .filter_map(|line| {
                let (kanji, reading) = line.split_once('\t')?;
                Some((kanji.chars().next()?, reading))
            })
            .collect()
    });
    READINGS.get(&kanji).copied()
}

/// Words IPADIC misreads, and their reading.
///
/// IPADIC reads words, and a name it has no entry for is read as the ordinary
/// words it is spelled like: 重音 is じゅうおん, "heavy sound", where Kasane Teto
/// is かさね. A word it lacks altogether, like 悪戯, is read kanji by kanji, and
/// a name it splits loses its voicing: 千本桜 is せんぼん and さくら, where the song
/// is Senbonzakura.
const KNOWN_READINGS: &[(&str, &str)] = &[
    ("千本桜", "せんぼんざくら"),
    ("重音", "かさね"),
    ("鏡音", "かがみね"),
    ("鳴花", "めいか"),
    ("星街", "ほしまち"),
    ("宵崎奏", "よいさきかなで"),
    ("雨路", "あめじ"),
    ("悪戯", "いたずら"),
];

/// Rewrite any [`KNOWN_READINGS`] name to its kana before segmenting.
fn with_known_readings(run: &str) -> String {
    if !KNOWN_READINGS
        .iter()
        .any(|(compound, _)| run.contains(compound))
    {
        return run.to_owned();
    }

    let mut patched = run.to_owned();
    for (compound, reading) in KNOWN_READINGS {
        patched = patched.replace(compound, reading);
    }
    patched
}

/// Transliteration is the most expensive step of a scan and repeats heavily
/// across an artist's folder, so results are kept.
fn cache() -> MutexGuard<'static, HashMap<String, String>> {
    static CACHE: LazyLock<Mutex<HashMap<String, String>>> =
        LazyLock::new(|| Mutex::new(HashMap::new()));
    // A cache cannot be left inconsistent by a panic elsewhere, so poisoning is
    // recovered from rather than propagated.
    CACHE.lock().unwrap_or_else(PoisonError::into_inner)
}
