r"""Dump the character classes Python's ``re`` uses, as fixtures for the Rust port.

The Rust port cannot reuse ``\w`` or ``\s``, and both differences are silent:

- ``\w``. Python's is ``str.isalnum()`` plus underscore -- categories L, Nd, Nl,
  No. Rust's ``regex`` uses ``\p{Word}``, which also includes ``\p{M}``: 10,549
  combining marks that Python treats as punctuation and folds to a space.
  ``[\p{L}\p{Nd}\p{Nl}\p{No}_]`` is the exact equivalent.
- ``\s``. Python's matches U+001C to U+001F, which are not ``White_Space`` and so
  are not matched by Rust's ``\s``.

Every comparison in the project flows through ``normalize()``, so a difference
here shifts matching scores globally rather than failing visibly.

The two fixtures written here are what the Rust suite checks its own predicates
against. ``assigned`` bounds the check: Rust's Unicode tables are newer than the
running Python's, and codepoints Python does not know cannot appear in anything
the oracle captured.

Usage: ``uv run --directory py python ../scripts/word_chars.py rs/crates/stk/tests/data``
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

SURROGATES = range(0xD800, 0xE000)

CLASSES = {
    "python_word_chars.txt": re.compile(r"\w", re.UNICODE),
    "python_space_chars.txt": re.compile(r"\s", re.UNICODE),
}


def ranges(matches: object) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    start: int | None = None
    for codepoint in range(0x110000):
        if codepoint not in SURROGATES and matches(codepoint):  # type: ignore[operator]
            if start is None:
                start = codepoint
        elif start is not None:
            found.append((start, codepoint - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def write(path: Path, description: str, found: list[tuple[int, int]]) -> None:
    lines = [
        f"# {description}\n",
        f"# Unicode {unicodedata.unidata_version}, via Python {sys.version_info.major}."
        f"{sys.version_info.minor}. Generated by scripts/word_chars.py.\n",
        *(f"{low:04X}..{high:04X}\n" for low, high in found),
    ]
    path.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    out = Path(sys.argv[1])
    for name, pattern in CLASSES.items():
        found = ranges(lambda cp, p=pattern: p.fullmatch(chr(cp)) is not None)  # type: ignore[misc]
        write(out / name, f"Codepoints matching {pattern.pattern} in Python's re.", found)

    assigned = ranges(lambda cp: unicodedata.category(chr(cp)) != "Cn")
    write(out / "python_assigned_chars.txt", "Codepoints assigned in Python's UCD.", assigned)


if __name__ == "__main__":
    main()
