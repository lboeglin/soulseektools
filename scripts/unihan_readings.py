"""Generate the kanji readings `text/romaji.rs` falls back on.

IPADIC reads words, not characters, and a kanji it has no entry for comes back
without a reading -- 号哭 as ``gou哭``, 幻樂団 as ``maboroshi樂団``. Unihan's
``kJapanese`` field gives every kanji its readings in kana, on'yomi in
katakana first and kun'yomi in hiragana after, so a character IPADIC cannot
read is given its first on'yomi: a lone kanji IPADIC does not know is almost
always part of a Sino-Japanese compound. Characters with only a kun'yomi get
that instead.

Only the ranges ``contains_japanese`` treats as kanji are kept, and every
reading is written in hiragana, which is what the kana table reads.

The data is under the Unicode licence; the header of the output records the
Unihan version it came from.

Usage: ``python scripts/unihan_readings.py Unihan_Readings.txt src/text/kanji_readings.tsv``

``Unihan_Readings.txt`` is in ``Unihan.zip``, at
https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

KANJI = ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF))
KATAKANA_TO_HIRAGANA = {cp: cp - 0x60 for cp in range(0x30A1, 0x30F7)}
HIRAGANA = re.compile(r"[ぁ-ゖー]+")


def is_kanji(codepoint: int) -> bool:
    return any(low <= codepoint <= high for low, high in KANJI)


def is_katakana(reading: str) -> bool:
    return "ァ" <= reading[0] <= "ヶ"


def first_reading(readings: list[str]) -> str | None:
    on = [r.translate(KATAKANA_TO_HIRAGANA) for r in readings if is_katakana(r)]
    kun = [r for r in readings if not is_katakana(r)]
    return next((r for r in on + kun if HIRAGANA.fullmatch(r)), None)


def main() -> None:
    source, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = source.read_text(encoding="utf-8")
    version = re.search(r"^# Unicode Version (\S+)", text, re.MULTILINE)

    lines = [
        "# The first Japanese reading of every kanji, in hiragana, from Unihan's kJapanese.\n",
        f"# Unicode {version.group(1) if version else 'unknown'}, under the Unicode licence."
        " Generated by scripts/unihan_readings.py.\n",
    ]
    for line in text.splitlines():
        if not line.startswith("U+"):
            continue
        codepoint, field, value = line.split("\t", 2)
        cp = int(codepoint[2:], 16)
        if field != "kJapanese" or not is_kanji(cp):
            continue
        reading = first_reading(value.split())
        if reading:
            lines.append(f"{chr(cp)}\t{reading}\n")

    out.write_text("".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
